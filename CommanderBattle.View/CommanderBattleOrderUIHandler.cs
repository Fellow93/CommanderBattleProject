using TaleWorlds.Core;
using TaleWorlds.Engine.GauntletUI;
using TaleWorlds.Library;
using TaleWorlds.MountAndBlade;
using TaleWorlds.MountAndBlade.ViewModelCollection.Order;

namespace CommanderBattle.View
{
    // The stock multiplayer order UI, which also serves the side's general (docs/plans/general-orders.md): his client
    // makes formations 0-7 his own for the bar (MissionMultiplayerCommanderBattleClient.GeneralCommand), so F1-F9
    // open it for him like for any commander. In general mode (CommanderBattleGeneralModeView) the display-dialog flag
    // it sets would stop the bar's input (GauntletOrderUIHandler.TickInput returns early on it), so that flag is lifted
    // around the bar's input while general mode owns it. Created directly in CommanderBattleMissionViews rather than
    // through MultiplayerViewCreator, which would create the stock handler.
    //
    // The bar's cards are named for their troops and commander ("Cataphracts (Fellow)", FormationNames) above the
    // card, and the selected card glows gold (Module/GUI/Prefabs/Order/OrderTroopItem.xml, which replaces Native's).
    public class CommanderBattleOrderUIHandler : TaleWorlds.MountAndBlade.Multiplayer.GauntletUI.Mission.MissionGauntletMultiplayerOrderUIHandler
    {
        private CommanderBattleGeneralModeView _generalMode;

        private MissionMultiplayerCommanderBattleClient _client;

        // The bar movie this handler loaded from the prefab XML (LoadBarFromXml).
        private GauntletMovieIdentifier _xmlBarMovie;

        // Each formation's card name, by formation index, for _labelSide.
        private readonly string[] _cardLabels = new string[CommanderBattleSettings.SlotCount];

        private BattleSideEnum _labelSide = BattleSideEnum.None;

        private bool _labelsDirty = true;

        public override void OnMissionScreenInitialize()
        {
            base.OnMissionScreenInitialize();
            _client = Mission.GetMissionBehavior<MissionMultiplayerCommanderBattleClient>();
            if (_client != null)
            {
                _client.Slots.OnSlotChanged += OnSlotChanged;
            }
        }

        public override void OnMissionScreenFinalize()
        {
            if (_client != null)
            {
                _client.Slots.OnSlotChanged -= OnSlotChanged;
            }
            base.OnMissionScreenFinalize();
        }

        // A new commander or troop class renames a card.
        private void OnSlotChanged(FormationSlot slot)
        {
            _labelsDirty = true;
        }

        public override void OnMissionScreenTick(float dt)
        {
            base.OnMissionScreenTick(dt);
            LoadBarFromXml();
            UpdateCardLabels();
        }

        // The stock bar movie ("OrderBar" for MissionOrderVM) is compiled into Native's
        // TaleWorlds.MountAndBlade.GauntletUI.AutoGenerated dlls, card prefab included, so it never reads
        // OrderTroopItem.xml and our replacement wouldn't show. GauntletMovie.Load takes the compiled one unless
        // generated prefabs are off, so the bar is loaded again with them off for this one load; every other movie
        // keeps the compiled path. The stock handler loads its movie on joining a team and again when the order type
        // option changes, each time compiled, hence the check every tick. The radial layout has no cards.
        private void LoadBarFromXml()
        {
            if (_movie == null || _movie == _xmlBarMovie || _movie.MovieName != _barOrderMovieName || _gauntletLayer == null || _dataSource == null)
            {
                return;
            }
            _gauntletLayer.ReleaseMovie(_movie);
            bool wasOff = UIConfig.DoNotUseGeneratedPrefabs;
            UIConfig.DoNotUseGeneratedPrefabs = true;
            try
            {
                _movie = _gauntletLayer.LoadMovie(_barOrderMovieName, _dataSource);
            }
            finally
            {
                UIConfig.DoNotUseGeneratedPrefabs = wasOff;
            }
            _xmlBarMovie = _movie;
        }

        // The stock card's name is its number (OrderTroopItemVM's constructor), which our card prefab shows above the
        // card in its place; the number key stays on the card's side (ApplySelectionKey). Cards are made again as
        // formations fill, so each is checked every tick.
        private void UpdateCardLabels()
        {
            if (_dataSource == null || _client == null)
            {
                return;
            }
            BattleSideEnum side = CommanderBattleTeams.MySide;
            if (side != _labelSide)
            {
                _labelSide = side;
                _labelsDirty = true;
            }
            if (_labelsDirty)
            {
                _labelsDirty = false;
                BasicCultureObject culture = CommanderBattleTeams.GetCulture(side);
                for (int i = 0; i < _cardLabels.Length; i++)
                {
                    FormationSlot slot = _client.Slots.GetSlot(side, i);
                    _cardLabels[i] = slot != null ? FormationNames.GetLabel(slot, culture) : null;
                }
            }
            MBList<OrderTroopItemVM> cards = _dataSource.TroopController.TroopList;
            for (int i = 0; i < cards.Count; i++)
            {
                OrderTroopItemVM card = cards[i];
                int index = card.Formation?.Index ?? -1;
                string label = index >= 0 && index < _cardLabels.Length ? _cardLabels[index] : null;
                if (label != null && card.FormationName != label)
                {
                    card.FormationName = label;
                }
            }
        }

        protected override void TickInput(float dt)
        {
            if (_generalMode == null)
            {
                _generalMode = Mission.GetMissionBehavior<CommanderBattleGeneralModeView>();
            }
            if (_generalMode == null || !_generalMode.LetsOrderBarTakeInput)
            {
                base.TickInput(dt);
                return;
            }
            MissionScreen.SetDisplayDialog(false);
            try
            {
                base.TickInput(dt);
            }
            finally
            {
                MissionScreen.SetDisplayDialog(true);
            }
        }
    }
}
